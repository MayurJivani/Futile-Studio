// node scripts/postal-geo.mjs <countries.json> <land-110m.json>
//
// Writes src/data/geo.js: country names and centre points for the postal
// model, and a dot-matrix land mask for the tracking map. Inputs are
// world-countries@5.1.0/countries.json and world-atlas@2.0.2/land-110m.json
// (Natural Earth, public domain). Run it again only if those change.
import process from 'node:process';
import { readFileSync, writeFileSync } from 'node:fs';

const [countriesPath, landPath] = process.argv.slice(2);
const countries = JSON.parse(readFileSync(countriesPath, 'utf8'));
const topo = JSON.parse(readFileSync(landPath, 'utf8'));

const table = Object.fromEntries(
	countries
		.filter((c) => /^[A-Z]{2}$/.test(c.cca2) && c.latlng?.length === 2)
		.sort((a, b) => a.cca2.localeCompare(b.cca2))
		.map((c) => [c.cca2, [c.name.common, ...c.latlng.map((n) => Math.round(n * 100) / 100)]]),
);

/* decode the quantised, delta-encoded topojson arcs into lon/lat rings */
const { scale, translate } = topo.transform;
const arcs = topo.arcs.map((arc) => {
	let x = 0;
	let y = 0;
	return arc.map(([dx, dy]) => [(x += dx) * scale[0] + translate[0], (y += dy) * scale[1] + translate[1]]);
});
/* rings that cross the antimeridian (Fiji, Chukotka) are unwrapped so each edge is short */
const ring = (ids) => {
	let shift = 0;
	let prev = null;
	return ids
		.flatMap((i) => (i < 0 ? [...arcs[~i]].reverse() : arcs[i]))
		.map(([x, y]) => {
			if (prev !== null && Math.abs(x + shift - prev) > 180) shift += prev > x + shift ? 360 : -360;
			prev = x + shift;
			return [prev, y];
		});
};
const rings = topo.objects.land.geometries.flatMap((g) =>
	(g.type === 'Polygon' ? [g.arcs] : g.arcs).flatMap((poly) => poly.map(ring)),
);
const inside = (lon, lat) => [lon - 360, lon, lon + 360].some((l) => crosses(l, lat));
const crosses = (lon, lat) => {
	let odd = false;
	for (const r of rings)
		for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
			const [xi, yi] = r[i];
			const [xj, yj] = r[j];
			if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) odd = !odd;
		}
	return odd;
};

/* 3 degree cells from 84N to 60S: Antarctica is not on any postal route */
const STEP = 3;
const TOP = 84;
const ROWS = 48;
const COLS = 120;
const land = [];
for (let r = 0; r < ROWS; r++) {
	let row = '';
	for (let c = 0; c < COLS; c++) row += inside(-180 + (c + 0.5) * STEP, TOP - (r + 0.5) * STEP) ? 'x' : '.';
	land.push(row);
}

writeFileSync(
	new URL('../src/data/geo.js', import.meta.url),
	`/* Generated by scripts/postal-geo.mjs from world-countries and Natural Earth
   (world-atlas land-110m). Do not edit by hand. */

/** ISO code: [name, latitude, longitude] of the country's centre. */
export const countries = ${JSON.stringify(table)};

/** Land, one character per ${STEP} degree cell, rows from ${TOP}N down. */
export const LAND = { step: ${STEP}, top: ${TOP}, rows: ${JSON.stringify(land, null, '\t')} };
`,
);
console.log(`geo: ${Object.keys(table).length} countries, ${land.join('').split('x').length - 1} land cells`);
